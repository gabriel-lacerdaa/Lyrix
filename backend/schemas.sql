-- Tabelas do Lyrix (PostgreSQL).
-- Criar manualmente:  psql -h localhost -p 5432 -U lyrix -d lyrix -f schemas.sql
-- O mapeamento SQLAlchemy em api/models/ precisa ficar igual a este arquivo.
-- IDs de songs e jobs são UUIDs em texto gerados pela API (uuid4).

BEGIN;

-- Músicas do acervo curado: vídeo do YouTube + letra sincronizada (LRC).
CREATE TABLE songs (
    id                  VARCHAR(36)  PRIMARY KEY,
    youtube_video_id    VARCHAR(11)  NOT NULL UNIQUE,
    title               VARCHAR(300) NOT NULL,
    artist              VARCHAR(300) NOT NULL,

    -- Dados do vídeo, vindos da YouTube Data API.
    video_title         VARCHAR(500) NOT NULL,
    channel_title       VARCHAR(300) NOT NULL,
    video_kind          VARCHAR(32)  NOT NULL
                        CHECK (video_kind IN ('topic', 'official_audio', 'clip')),
    video_duration_ms   INTEGER      NOT NULL CHECK (video_duration_ms > 0),
    thumbnail_url       VARCHAR(500),

    -- Letra e sincronização.
    lyrics_plain        TEXT,
    lrc_raw             TEXT,
    -- Quanto o vídeo está atrasado em relação ao LRC: tempoDaLetra = tempoDoVídeo - offset_ms.
    offset_ms           INTEGER      NOT NULL DEFAULT 0,
    sync_source         VARCHAR(32)
                        CHECK (sync_source IN ('lrclib', 'stable_ts', 'manual')),
    -- ID do vídeo cujo áudio foi usado para medir o LRC (NULL quando veio pronto da LRCLIB).
    synced_on_video_id  VARCHAR(11),
    sync_warnings       JSONB        NOT NULL DEFAULT '[]'::jsonb,
    -- Versões alternativas para a revisão: {"lrclib": "...", "aligned": "...", "lrclib_estimated_offset_ms": 0}.
    lrc_candidates      JSONB        NOT NULL DEFAULT '{}'::jsonb,

    status              VARCHAR(32)  NOT NULL DEFAULT 'draft'
                        CHECK (status IN ('draft', 'processing', 'waiting_lyrics', 'ready_for_review',
                                          'failed', 'published', 'broken')),
    cefr_level          VARCHAR(2)
                        CHECK (cefr_level IN ('A1', 'A2', 'B1', 'B2', 'C1', 'C2')),

    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),  -- atualizado pela API a cada alteração
    reviewed_at         TIMESTAMPTZ,
    published_at        TIMESTAMPTZ
);

CREATE INDEX ix_songs_status ON songs (status);

-- Linhas da letra com o tempo de início, geradas a partir de songs.lrc_raw.
-- Texto vazio = trecho instrumental (apaga o destaque no app).
CREATE TABLE lyric_lines (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    song_id     VARCHAR(36) NOT NULL REFERENCES songs (id) ON DELETE CASCADE,
    line_index  INTEGER     NOT NULL CHECK (line_index >= 0),
    start_ms    INTEGER     NOT NULL,
    text        TEXT        NOT NULL,
    CONSTRAINT uq_lyric_lines_song_line UNIQUE (song_id, line_index)
);

-- Fila de processamento (busca da letra e geração do LRC), consumida pelo worker.
CREATE TABLE jobs (
    id           VARCHAR(36) PRIMARY KEY,
    song_id      VARCHAR(36) NOT NULL REFERENCES songs (id) ON DELETE CASCADE,
    method       VARCHAR(32) NOT NULL DEFAULT 'auto'
                 CHECK (method IN ('auto', 'lrclib', 'align')),
    status       VARCHAR(32) NOT NULL DEFAULT 'queued'
                 CHECK (status IN ('queued', 'running', 'done', 'failed')),
    step         VARCHAR(50),
    log          TEXT        NOT NULL DEFAULT '',
    error        TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    started_at   TIMESTAMPTZ,
    finished_at  TIMESTAMPTZ
);

CREATE INDEX ix_jobs_song_id ON jobs (song_id);
-- O worker busca a próxima tarefa com status = 'queued' ORDER BY created_at.
CREATE INDEX ix_jobs_status_created_at ON jobs (status, created_at);

-- Cache das traduções sob demanda (POST /translate), por trecho: uma palavra ou uma frase curta.
-- Nunca guarda a letra inteira traduzida. Compartilhado entre usuários.
-- key_hash = SHA-256 de "kind|source_lang|target_lang|texto normalizado" (minúsculas, apóstrofo reto, espaços únicos).
CREATE TABLE translation_cache (
    key_hash     VARCHAR(64) PRIMARY KEY,
    kind         VARCHAR(32) NOT NULL CHECK (kind IN ('word', 'phrase')),
    source_lang  VARCHAR(8)  NOT NULL,
    target_lang  VARCHAR(8)  NOT NULL,
    source_text  TEXT        NOT NULL,
    translation  TEXT        NOT NULL,
    provider     VARCHAR(32) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMIT;
